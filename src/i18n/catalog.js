// Translated display names for catalog DATA that must stay English in the tables themselves
// (docs/design/localization.md): filters, effects, transitions, LUTs, text templates, animations, blend
// modes, mask shapes, crop aspects, playback quality levels and the transition collections. The agent
// tools match user requests against the English names and projects persist them, so the tables are never
// edited; the UI asks here for what to SHOW. Keys are `catalog.<kind>.<slug>` with the slug built from the
// item's id (its file for a LUT, its slug for a collection item, the text itself for a category or group
// name); a missing key falls back to the English name, so the UI never shows a bare key. The keys are
// generated by scripts/i18n-catalog-keys.cjs into shared/i18n/parts/catalog.en.json.
import { t } from './index.js';

// 'Glitch & Digital' -> 'glitch_digital', 'slay-01-amber.cube' -> 'slay_01_amber_cube', '16:9' -> '16_9'.
export const catalogSlug = (s) => String(s ?? '').toLowerCase().replace(/[^a-z0-9]+/g, '_').replace(/^_+|_+$/g, '');
export const catalogKey = (kind, id) => `catalog.${kind}.${catalogSlug(id)}`;

// The text of a key, or `english` (with {params} filled) when the dictionary has no such key.
const pick = (key, english, params) => {
  const s = t(key, params);
  if (s !== key) return s;
  return params ? String(english).replace(/\{(\w+)\}/g, (m, k) => (params[k] === undefined || params[k] === null ? m : String(params[k]))) : english;
};

// The id a catalog item is keyed by: id, else file (LUTs), else slug (collection items), else its name.
const idOf = (item) => item.id ?? item.file ?? item.slug ?? item.name ?? item.label;

// Display name of a catalog item ({ id, name } or { file, name } or { id, label }), English when untranslated.
export function catalogName(kind, item) {
  if (!item) return '';
  const english = item.name ?? item.label ?? '';
  return pick(catalogKey(kind, idOf(item)), english);
}

// Display text of a category / group name that is its own id ('Film & Vintage', 'Captions', 'Basic').
export function catalogLabel(kind, text) {
  if (text === undefined || text === null || text === '') return text;
  return pick(catalogKey(kind, text), text);
}

// Display name of a clip's filter id as src/features/effects/filters.js filterName() labels it: a look id
// ('vivid'), or a bundled LUT used as the filter ('lut:<file>', shown as "<LUT name> (LUT)"). `english` is
// filterName(id), the English fallback.
export function filterLabel(id, english) {
  const s = String(id ?? '');
  if (s.startsWith('lut:')) {
    const base = pick(catalogKey('lut', s.slice(4)), String(english ?? '').replace(/ \(LUT\)$/, ''));
    return pick('catalog.lut_filter', '{name} (LUT)', { name: base });
  }
  return pick(catalogKey('filter', s), english ?? s);
}

// Display name of an effect from effectInfo() (src/features/effects/effects.js): a catalog effect, or a
// filter look placed on the Effects track (group 'Filters', id 'filter:<look>', English "<look> filter").
export function effectLabel(info, fallback = '') {
  if (!info) return fallback;
  if (info.group === 'Filters') {
    const look = String(info.id ?? '').slice('filter:'.length);
    const name = filterLabel(look, String(info.name ?? '').replace(/ filter$/, ''));
    return pick('catalog.filter_layer', '{name} filter', { name });
  }
  return catalogName('effect', info);
}
