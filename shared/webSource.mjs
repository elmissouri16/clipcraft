// Shared by chat rendering and the main-process browser opener. Never allow
// citations to open local files, scripts or credential-bearing URLs.
export function webSourceUrl(value) {
  if (typeof value !== 'string' || value.length > 8192 || /[\u0000-\u0020\u007f]/.test(value)) return null;
  try {
    const url = new URL(value);
    return ['https:', 'http:'].includes(url.protocol) && !url.username && !url.password ? url.href : null;
  } catch { return null; }
}
