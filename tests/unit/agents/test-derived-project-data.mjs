import assert from 'node:assert/strict';
import { emptyProject, historyReducer } from '../../../src/state/store.js';
import { projectRevision } from '../../../src/features/agent/context.js';
let state = { past: [], future: [], present: emptyProject() };
const id = state.present.id, initial = projectRevision(state.present);
state = historyReducer(state, { type: 'beginAgentEdit', token: 'agent' });
state = historyReducer(state, { type: 'setProject', patch: { name: 'Agent edit' }, agentToken: 'agent' });
const revision = projectRevision(state.present);
state = historyReducer(state, { type: 'projectVisuals', projectId: id, patch: { posterImage: '/preview.jpg', posterImageAt: 1234 } });
assert.equal(state.agentEdit.token, 'agent');assert.equal(state.agentEdit.steps.length, 1);assert.equal(projectRevision(state.present), revision);
state = historyReducer(state, { type: 'endAgentEdit', token: 'agent' });
assert.equal(state.past.length, 1);
state = historyReducer(state, { type: 'undo' });assert.equal(projectRevision(state.present), initial);assert.equal(state.present.posterImage, '/preview.jpg');
state = historyReducer(state, { type: 'redo' });assert.equal(state.present.name, 'Agent edit');assert.equal(state.present.posterImageAt, 1234);
const current = state;
state = historyReducer(state, { type: 'projectVisuals', projectId: 'another-project', patch: { posterImage: '/stale.jpg' } });assert.equal(state, current);
state = historyReducer(state, { type: 'projectVisuals', projectId: id, patch: { name: 'Hidden edit' } });assert.equal(state, current);
state = historyReducer(state, { type: 'projectVisuals', projectId: id, patch: { posterImageAt: NaN } });assert.equal(state, current);
state = historyReducer(state, { type: 'beginAgentEdit', token: 'second-agent' });
state = historyReducer(state, { type: 'setProject', patch: { name: 'Actual user edit' } });assert.equal(state.agentEdit, undefined);assert.equal(state.agentInterruption.action, 'setProject');
const manual = state;
state = historyReducer(state, { type: 'setProject', patch: { name: 'Late agent result' }, agentToken: 'second-agent' });assert.equal(state, manual);
console.log('Derived project data: cover updates preserve request ownership, semantic revision and Undo; foreign callbacks and manual changes remain guarded.');
